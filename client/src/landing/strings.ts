/** Per game language code: the BCP 47 tag (html lang, number and date formats) and the table. */
export const LOCALES: Readonly<Record<number, { tag: string; table: Table }>> = {
  1: { tag: "en-US", table: en },
  2: { tag: "en-GB", table: enGB },
  3: { tag: "fr", table: fr },
  4: { tag: "de", table: de },
  5: { tag: "it", table: it },
  6: { tag: "es", table: es },
  7: { tag: "nl", table: nl },
  8: { tag: "da", table: da },
  9: { tag: "sv", table: sv },
  10: { tag: "nb", table: no },
  11: { tag: "fi", table: fi },
  14: { tag: "pt-BR", table: pt },
  15: { tag: "ja", table: ja },
  16: { tag: "pl", table: pl },
  17: { tag: "zh-CN", table: zhCN },
  18: { tag: "zh-TW", table: zhTW },
  19: { tag: "th", table: th },
  20: { tag: "ko", table: ko },
};

let current = LOCALES[1]!;
let plurals = new Intl.PluralRules(current.tag);

export function setLocale(code: number): void {
  current = LOCALES[code] ?? LOCALES[1]!;
  plurals = new Intl.PluralRules(current.tag);
}

export function localeTag(): string {
  return current.tag;
}

/** The message `key` in the current language, `{name}` filled from `vars` (a plural one picks its form by `vars.n`). */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const msg: Msg = current.table[key] ?? en[key];
  let s: string;
  if (typeof msg === "string") s = msg;
  else {
    const n = Number(vars["n"] ?? vars["m"] ?? 0);
    s = msg[plurals.select(n)] ?? msg.other;
  }
  return s.replace(/\{(\w+)\}/g, (all, name: string) => {
    const v = vars[name];
    if (v === undefined) return all;
    return typeof v === "number" ? v.toLocaleString(current.tag) : v;
  });
}

/** The byte units per language (French and Finnish write octets / tavut). */
const UNITS: Readonly<Record<string, readonly [string, string, string, string]>> = {
  fr: ["o", "Ko", "Mo", "Go"],
  fi: ["t", "kt", "Mt", "Gt"],
};

export function formatBytes(n: number): string {
  const [b, k, m, g] = UNITS[current.tag] ?? ["B", "KB", "MB", "GB"];
  const num = (v: number, d: number): string => v.toLocaleString(current.tag, { minimumFractionDigits: d, maximumFractionDigits: d });
  if (n < 1024) return `${num(n, 0)} ${b}`;
  if (n < 1024 * 1024) return `${num(n / 1024, 1)} ${k}`;
  if (n < 1024 * 1024 * 1024) return `${num(n / 1024 / 1024, 1)} ${m}`;
  return `${num(n / 1024 / 1024 / 1024, 2)} ${g}`;
}
